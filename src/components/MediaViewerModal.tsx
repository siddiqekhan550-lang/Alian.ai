import React, { useState } from 'react';
import { Generation } from '../types/index.js';
import {
  X,
  Download,
  Copy,
  Check,
  RotateCcw,
  Trash2,
  Sparkles,
  Film,
  Image as ImageIcon,
  Clock,
  Layers,
  Coins,
} from 'lucide-react';

interface MediaViewerModalProps {
  generation: Generation | null;
  isOpen: boolean;
  onClose: () => void;
  onRegenerate?: (prompt: string, type: 'image' | 'video', duration?: number, ratio?: string) => void;
  onDelete?: (id: string) => void;
}

export const MediaViewerModal: React.FC<MediaViewerModalProps> = ({
  generation,
  isOpen,
  onClose,
  onRegenerate,
  onDelete,
}) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen || !generation) return null;

  const handleCopyPrompt = () => {
    navigator.clipboard.writeText(generation.prompt);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const url = generation.output_url || generation.thumbnail_url;
    if (!url) return;

    const a = document.createElement('a');
    a.href = url;
    a.download = `alien-ai-${generation.type}-${generation.id}.${generation.type === 'video' ? 'mp4' : 'jpg'}`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/85 backdrop-blur-md animate-in fade-in duration-200">
      <div className="relative w-full max-w-4xl max-h-[90vh] bg-[#14111F] border border-white/10 rounded-2xl shadow-2xl overflow-hidden flex flex-col md:flex-row">
        {/* Close Button */}
        <button
          onClick={onClose}
          className="absolute top-4 right-4 z-10 p-2 text-[#A29CB8] hover:text-white rounded-xl bg-black/40 hover:bg-black/60 transition-colors cursor-pointer"
        >
          <X className="w-5 h-5" />
        </button>

        {/* Media Preview Area */}
        <div className="w-full md:w-3/5 bg-[#07060D] flex items-center justify-center p-4 relative min-h-[300px] md:min-h-[500px]">
          {generation.type === 'video' ? (
            generation.output_url?.endsWith('.mp4') || generation.output_url?.includes('video') ? (
              <video
                src={generation.output_url}
                controls
                autoPlay
                loop
                className="max-h-[75vh] w-auto max-w-full rounded-xl object-contain shadow-2xl"
              />
            ) : (
              <div className="relative group max-h-[75vh] w-full flex items-center justify-center">
                <img
                  src={generation.output_url || generation.thumbnail_url}
                  alt={generation.prompt}
                  className="max-h-[75vh] w-auto max-w-full rounded-xl object-contain shadow-2xl"
                />
                <div className="absolute inset-0 flex items-center justify-center bg-black/40 rounded-xl">
                  <div className="p-4 rounded-full bg-[#7C5CFF]/80 text-white flex items-center gap-2">
                    <Film className="w-6 h-6" />
                    <span className="text-xs font-semibold">Video Preview Scene</span>
                  </div>
                </div>
              </div>
            )
          ) : (
            <img
              src={generation.output_url || generation.thumbnail_url}
              alt={generation.prompt}
              className="max-h-[75vh] w-auto max-w-full rounded-xl object-contain shadow-2xl"
            />
          )}

          {/* Provider badge */}
          <div className="absolute bottom-3 left-3 px-2.5 py-1 rounded-lg bg-black/60 backdrop-blur-md border border-white/10 text-[10px] text-[#22E6A8] uppercase font-bold tracking-wider flex items-center gap-1.5">
            <Sparkles className="w-3 h-3" />
            <span>Generated by {generation.provider.toUpperCase()}</span>
          </div>
        </div>

        {/* Sidebar Info & Controls */}
        <div className="w-full md:w-2/5 p-6 flex flex-col justify-between overflow-y-auto">
          <div>
            <div className="flex items-center gap-2 mb-3">
              <span
                className={`px-2 py-0.5 rounded-full text-[10px] font-bold uppercase tracking-wider ${
                  generation.type === 'video'
                    ? 'bg-purple-500/20 text-purple-300 border border-purple-500/30'
                    : 'bg-cyan-500/20 text-cyan-300 border border-cyan-500/30'
                }`}
              >
                {generation.type}
              </span>
              <span className="text-xs text-[#A29CB8]">
                {new Date(generation.created_at).toLocaleDateString()}
              </span>
            </div>

            <h3 className="text-sm font-semibold text-white mb-2">Prompt</h3>
            <div className="p-3 bg-[#07060D] border border-white/5 rounded-xl text-xs text-[#F4F2FB] leading-relaxed relative group mb-4">
              <p>{generation.prompt}</p>
              <button
                onClick={handleCopyPrompt}
                className="mt-2 text-[11px] text-[#7C5CFF] hover:text-[#22E6A8] flex items-center gap-1 cursor-pointer font-medium"
              >
                {copied ? <Check className="w-3.5 h-3.5 text-[#22E6A8]" /> : <Copy className="w-3.5 h-3.5" />}
                <span>{copied ? 'Copied to Clipboard' : 'Copy Prompt'}</span>
              </button>
            </div>

            {/* Metadata specs */}
            <h4 className="text-xs font-semibold text-[#A29CB8] uppercase tracking-wider mb-2">
              Specifications
            </h4>
            <div className="space-y-2 text-xs bg-[#07060D] p-3 rounded-xl border border-white/5 mb-6">
              {generation.duration && (
                <div className="flex items-center justify-between text-[#A29CB8]">
                  <span className="flex items-center gap-1.5"><Clock className="w-3.5 h-3.5 text-[#7C5CFF]" /> Duration</span>
                  <span className="text-white font-medium">{generation.duration} Seconds</span>
                </div>
              )}
              <div className="flex items-center justify-between text-[#A29CB8]">
                <span className="flex items-center gap-1.5"><Layers className="w-3.5 h-3.5 text-[#22E6A8]" /> Aspect Ratio</span>
                <span className="text-white font-medium">{generation.aspect_ratio}</span>
              </div>
              <div className="flex items-center justify-between text-[#A29CB8]">
                <span className="flex items-center gap-1.5"><Coins className="w-3.5 h-3.5 text-amber-400" /> Cost Deducted</span>
                <span className="text-white font-medium">{generation.credits_charged} Credits</span>
              </div>
              <div className="flex items-center justify-between text-[#A29CB8]">
                <span>Status</span>
                <span className="text-[#22E6A8] font-bold capitalize">{generation.status}</span>
              </div>
            </div>
          </div>

          {/* Action buttons */}
          <div className="space-y-2 pt-4 border-t border-white/5">
            <button
              onClick={handleDownload}
              className="w-full py-2.5 px-4 rounded-xl font-semibold text-xs text-white bg-gradient-to-r from-[#7C5CFF] to-[#B05CFF] hover:from-[#8C6DFF] hover:to-[#BD73FF] shadow-lg shadow-[#7C5CFF]/20 flex items-center justify-center gap-2 cursor-pointer"
            >
              <Download className="w-4 h-4" />
              <span>Download Media</span>
            </button>

            <div className="flex gap-2">
              <button
                onClick={() => {
                  onRegenerate?.(
                    generation.prompt,
                    generation.type,
                    generation.duration,
                    generation.aspect_ratio
                  );
                  onClose();
                }}
                className="flex-1 py-2 px-3 rounded-xl text-xs font-medium text-white bg-white/5 hover:bg-white/10 border border-white/10 flex items-center justify-center gap-1.5 cursor-pointer"
              >
                <RotateCcw className="w-3.5 h-3.5 text-[#22E6A8]" />
                <span>Regenerate</span>
              </button>

              <button
                onClick={() => {
                  if (confirm('Are you sure you want to delete this creation from your history?')) {
                    onDelete?.(generation.id);
                    onClose();
                  }
                }}
                className="py-2 px-3 rounded-xl text-xs font-medium text-red-400 hover:bg-red-500/10 border border-red-500/20 flex items-center justify-center gap-1.5 cursor-pointer"
              >
                <Trash2 className="w-3.5 h-3.5" />
                <span>Delete</span>
              </button>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};
